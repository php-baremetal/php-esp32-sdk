    public function test_project_version_comes_from_composer_then_git_then_fallback(): void
    {
        $dir = sys_get_temp_dir() . '/php-esp32-sdk-ver-' . bin2hex(random_bytes(4));
        mkdir($dir);
        try {
            $git = (new FakeProcess())
                ->on('git rev-parse --show-toplevel', new ProcessResult(0, "{$dir}/.\n"))
                ->on('git describe --tags --always', new ProcessResult(0, "v1.2.0-3-gabc1234;x\n"));
            self::assertSame('0.0.0', ProjectVersion::of($dir));
            self::assertSame('0.0.0', ProjectVersion::of($dir, new FakeProcess()));
            self::assertSame('v1.2.0-3-gabc1234x', ProjectVersion::of($dir, $git));
            self::assertSame(['git', 'rev-parse', '--show-toplevel'], $git->calls[0]);
            self::assertSame(['git', 'describe', '--tags', '--always'], $git->calls[1]);
            $outer = (new FakeProcess())
                ->on('git rev-parse --show-toplevel', new ProcessResult(0, sys_get_temp_dir() . "\n"))
                ->on('git describe --tags --always', new ProcessResult(0, "v9.9.9\n"));
            self::assertSame('0.0.0', ProjectVersion::of($dir, $outer));
            self::assertCount(1, $outer->calls);
            file_put_contents("{$dir}/composer.json", json_encode(['name' => 'a/b', 'version' => '2.1.0']));
            self::assertSame('2.1.0', ProjectVersion::of($dir, $git));
            file_put_contents("{$dir}/composer.json", json_encode(['name' => 'a/b', 'version' => '2.1;0']));
            self::assertSame('2.10', ProjectVersion::of($dir));
            file_put_contents("{$dir}/composer.json", json_encode(['name' => 'a/b', 'version' => str_repeat('9', 40)]));
            self::assertSame(str_repeat('9', 31), ProjectVersion::of($dir));
            $plan = Plans::plan();
            $inputs = (string) file_get_contents(BuildInputs::write($plan, null, '2.1.0'));
            self::assertStringContainsString("set(PHPBM_PROJECT_VER \"2.1.0\")\n", $inputs);
        } finally {
            @unlink("{$dir}/composer.json");
            @rmdir($dir);
        }
    }

