    public function test_describes_the_packages(): void
    {
        $plan = Plans::plan();
        $project = $plan->projectDir;
        $fixtures = __DIR__ . '/fixtures/packages';
        foreach (['hal/src/a.c', 'hal/src/b.c', 'cfg/sdkconfig.esp32'] as $file) {
            @mkdir(dirname("{$project}/vendor/{$file}"), 0777, true);
            copy("{$fixtures}/{$file}", "{$project}/vendor/{$file}");
        }
        $plan = Plans::plan(['packages' => [
            new Package('acme/esp32-hal', 'bm-hal', '1.0.0', 'vendor\\hal', ['platform' => 'esp32', 'partitions' => [['name' => 'phpstore', 'subtype' => 'nvs', 'size' => '24K'], ['name' => 'logs', 'subtype' => 'fat', 'size' => '64K']]]),
            new Package('acme/cfg', 'bm-lib', '2.0.0', './vendor/cfg', ['sdkconfig' => 'sdkconfig.esp32']),
        ]]);
        $plan = new BuildPlan($project, $plan->manifest, $plan->sdk, $plan->board, $plan->chip, $plan->runtime, $plan->storage, $plan->php, $plan->phpSourceDir, $plan->sourceDirs, $plan->env, $plan->buildDir);
        $inputs = (string) file_get_contents(BuildInputs::write($plan));

        self::assertStringContainsString("set(PHPBM_PARTITIONS \"phpstore,nvs,24;logs,fat,64\")\n", $inputs);
        self::assertStringContainsString("set(PHPBM_PACKAGE_SDKCONFIG \"{$project}/vendor/cfg/sdkconfig.esp32\")\n", $inputs);
        self::assertStringNotContainsString('PHPBM_PACKAGES ', $inputs);
        self::assertStringNotContainsString('PHPBM_PACKAGE_0', $inputs);
        preg_match('/set\(PHPBM_PREFIX_MAPS "([^"]*)"\)/', $inputs, $m);
        $maps = explode(';', $m[1]);
        $position = static fn (string $map): int|false => array_search($map, $maps, true);
        self::assertNotFalse($position("{$project}=project"));
        self::assertGreaterThan($position("{$project}=project"), $position("{$project}/vendor/hal=package/acme/esp32-hal"));
        self::assertGreaterThan($position("{$project}=project"), $position("{$project}/vendor/cfg=package/acme/cfg"));
        self::assertStringContainsString('"' . $project . '/vendor/hal/src/a.c"', (string) file_get_contents("{$plan->buildDir}/phpbm_packages/CMakeLists.txt"));
    }

