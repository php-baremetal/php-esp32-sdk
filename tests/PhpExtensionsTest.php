<?php

declare(strict_types=1);

namespace PhpBaremetal\Esp32\Tests;

use PhpBaremetal\Esp32\BuildInputs;
use PhpBaremetal\Esp32\PhpExtensions;
use PhpBaremetal\Esp32\Tests\Support\Plans;
use PhpBaremetal\Spec\Sdk\BuildPlan;
use PhpBaremetal\Spec\Sdk\Descriptor\PhpExtension;
use PhpBaremetal\Spec\Sdk\Sdk;
use PhpBaremetal\Spec\SpecException;
use PHPUnit\Framework\TestCase;

final class PhpExtensionsTest extends TestCase
{
    private static function dir(): string
    {
        return BuildInputs::cmakePath(__DIR__ . '/fixtures/php-ext');
    }

    private static function extension(string $name, array $override = []): PhpExtension
    {
        $data = json_decode((string) file_get_contents(self::dir() . "/extensions/{$name}.json"), true);
        return PhpExtension::fromArray('8.4', $name, [...$data, ...$override], "{$name}.json");
    }

    /** @param array<string,string|int|bool> $options */
    private static function plan(array $options = [], ?array $extensions = null): BuildPlan
    {
        return Plans::plan([
            'php' => self::dir() . '/php-src',
            'sources' => ['onig' => self::dir() . '/onig'],
            'phpExtensions' => $extensions ?? [self::extension('base'), self::extension('fake')],
            'options' => $options,
        ]);
    }

    public function test_resolves_sources_includes_and_defines(): void
    {
        $d = self::dir();
        $extensions = PhpExtensions::fromPlan(self::plan());
        self::assertSame(['base', 'fake'], $extensions->names());
        self::assertSame([
            "{$d}/php-src/ext/base/base.c",
            "{$d}/php-src/ext/fake/fake.c",
            "{$d}/php-src/ext/fake/fake_cjk.c",
            "{$d}/php-src/ext/fake/lib/a.c",
            "{$d}/onig/src/regcomp.c",
        ], $extensions->sources);
        self::assertSame(["{$d}/php-src/ext/base", "{$d}/php-src/ext/fake", "{$d}/onig/src"], $extensions->includeDirs);
        self::assertSame(['HAVE_BASE=1', 'HAVE_FAKE=1'], $extensions->definitions());
    }

    public function test_the_options_header_names_the_active_extensions_and_storage(): void
    {
        $plan = self::plan();
        BuildInputs::write($plan);
        $header = (string) file_get_contents($plan->buildDir . '/include/phpbm_options.h');
        self::assertStringContainsString("#define PHPBM_PHP_EXT_BASE 1\n#define PHPBM_PHP_EXT_FAKE 1\n#define PHPBM_PHP_STARTUP_KB 816\n#define PHPBM_PHP_EXT_STARTUP_KB 0\n#define PHPBM_NETWORK_ENABLED", $header);
        self::assertStringNotContainsString('PHPBM_STORAGE_MICROSD', $header);

        $plan = Plans::plan(['storage' => 'microsd']);
        BuildInputs::write($plan);
        self::assertStringContainsString("#define PHPBM_STORAGE_MICROSD 1\n#define PHPBM_NETWORK_ENABLED", (string) file_get_contents($plan->buildDir . '/include/phpbm_options.h'));
    }

    public function test_the_options_header_sums_the_startup_memory_of_the_active_extensions(): void
    {
        $when = ['x-big' => ['description' => 'b', 'type' => 'bool', 'default' => false, 'when' => ['true' => ['startup-kb' => 8]]]];
        $plan = self::plan([], [self::extension('base', ['startup-kb' => 3]), self::extension('fake', ['startup-kb' => 20, 'options' => $when])]);
        BuildInputs::write($plan);
        self::assertStringContainsString("#define PHPBM_PHP_EXT_STARTUP_KB 23\n", (string) file_get_contents($plan->buildDir . '/include/phpbm_options.h'));
        $plan = self::plan(['x-big' => true], [self::extension('base', ['startup-kb' => 3]), self::extension('fake', ['startup-kb' => 20, 'options' => $when])]);
        BuildInputs::write($plan);
        self::assertStringContainsString("#define PHPBM_PHP_EXT_STARTUP_KB 31\n", (string) file_get_contents($plan->buildDir . '/include/phpbm_options.h'));
    }

    public function test_options_apply_their_when(): void
    {
        $d = self::dir();
        $extensions = PhpExtensions::fromPlan(self::plan(['fake-cjk' => false, 'fake-tables' => 'big']));
        self::assertSame([
            "{$d}/php-src/ext/base/base.c",
            "{$d}/php-src/ext/fake/fake.c",
            "{$d}/php-src/ext/fake/lib/a.c",
            "{$d}/onig/src/regcomp.c",
            "{$d}/php-src/ext/fake/fake_big.c",
            "{$d}/onig/src/regexec.c",
        ], $extensions->sources);
        self::assertSame(["{$d}/php-src/ext/base", "{$d}/php-src/ext/fake", "{$d}/onig/src", "{$d}/php-src/ext/fake/lib"], $extensions->includeDirs);
        self::assertSame(['FAKE_NO_CJK=1', 'FAKE_TABLES=big', 'HAVE_BASE=1', 'HAVE_FAKE=1'], $extensions->definitions());
    }

    public function test_generates_the_module_table_in_registration_order(): void
    {
        self::assertSame(<<<'C'
            /* Generated by phpbm from the project's bm-php-ext packages. */
            #include "php.h"
            #include "zend_modules.h"

            extern zend_module_entry base_module_entry;
            extern zend_module_entry fake_module_entry;

            zend_module_entry *const phpbm_php_extensions[] = {
                &base_module_entry,
                &fake_module_entry,
            };
            const int phpbm_php_extension_count = 2;

            C, PhpExtensions::fromPlan(self::plan())->tableSource());
    }

    public function test_the_compat_sources_of_an_extension_are_compiled(): void
    {
        $real = SdkDescriptorsTest::sdk();
        $sdk = new Sdk(self::dir() . '/sdk', $real->descriptor, $real->chips, $real->boards, $real->runtimes, $real->storages);
        $port = PhpExtension::fromArray('8.4', 'port', ['module' => 'port', 'entry' => null, 'sources' => ['ext/base/base.c']], 'port.json');
        $plan = Plans::plan(['sdk' => $sdk, 'php' => self::dir() . '/php-src', 'phpExtensions' => [$port]]);
        $compat = self::dir() . '/sdk/php/8.4/compat/extensions/port';
        self::assertSame([
            self::dir() . '/php-src/ext/base/base.c',
            "{$compat}/a_stubs.c",
            "{$compat}/b_backend.c",
        ], PhpExtensions::fromPlan($plan)->sources);
    }

    public function test_an_extension_can_be_all_compat_code_and_require_idf_components(): void
    {
        $real = SdkDescriptorsTest::sdk();
        $sdk = new Sdk(self::dir() . '/sdk', $real->descriptor, $real->chips, $real->boards, $real->runtimes, $real->storages);
        $port = PhpExtension::fromArray('8.4', 'port', ['module' => 'port', 'idf-requires' => ['mbedtls']], 'port.json');
        $base = self::extension('base', ['idf-requires' => ['mbedtls', 'espressif__zlib']]);
        $plan = Plans::plan(['sdk' => $sdk, 'php' => self::dir() . '/php-src', 'phpExtensions' => [$port, $base]]);
        $extensions = PhpExtensions::fromPlan($plan);
        $compat = self::dir() . '/sdk/php/8.4/compat/extensions/port';
        self::assertSame(["{$compat}/a_stubs.c", "{$compat}/b_backend.c", self::dir() . '/php-src/ext/base/base.c'], $extensions->sources);
        self::assertSame(['espressif__zlib', 'mbedtls'], $extensions->idfRequires);
        $inputs = (string) file_get_contents(BuildInputs::write($plan));
        self::assertStringContainsString("set(PHPBM_PHP_EXT_IDF_REQUIRES \"espressif__zlib;mbedtls\")\n", $inputs);
    }

    public function test_an_extension_that_compiles_nothing_is_an_sdk_bug(): void
    {
        $empty = PhpExtension::fromArray('8.4', 'empty', ['module' => 'empty'], 'empty.json');
        $this->expectExceptionMessage("php/8.4/extensions/empty.json: the extension compiles no file (no 'sources' and no compat/extensions/empty/*.c)");
        PhpExtensions::fromPlan(self::plan([], [$empty]));
    }

    public function test_an_extension_with_a_null_entry_stays_out_of_the_table(): void
    {
        $zend = PhpExtension::fromArray('8.4', 'zend', ['module' => 'zend', 'entry' => null, 'sources' => ['ext/base/base.c']], 'zend.json');
        $table = PhpExtensions::fromPlan(self::plan([], [$zend, self::extension('fake')]))->tableSource();
        self::assertStringContainsString("    &fake_module_entry,\n};\nconst int phpbm_php_extension_count = 1;", $table);
        self::assertStringEndsWith("phpbm_php_extensions[] = {\n    NULL,\n};\nconst int phpbm_php_extension_count = 0;\n", PhpExtensions::fromPlan(self::plan([], [$zend]))->tableSource());
        $custom = PhpExtension::fromArray('8.4', 'zz', ['module' => 'zz', 'entry' => 'php_zz_module_entry', 'sources' => ['ext/base/base.c']], 'zz.json');
        $table = PhpExtensions::fromPlan(self::plan([], [$custom]))->tableSource();
        self::assertStringContainsString("extern zend_module_entry php_zz_module_entry;\n", $table);
        self::assertStringContainsString("    &php_zz_module_entry,\n", $table);
    }

    public function test_build_inputs_carry_the_extensions(): void
    {
        $d = self::dir();
        $plan = self::plan(['fake-cjk' => false]);
        $inputs = (string) file_get_contents(BuildInputs::write($plan));
        $build = $plan->buildDir;
        self::assertStringContainsString("set(PHPBM_PHP_EXTENSIONS \"base;fake\")\n", $inputs);
        self::assertStringContainsString("set(PHPBM_PHP_EXT_TABLE \"{$build}/php_extensions.c\")\n", $inputs);
        self::assertStringContainsString("set(PHPBM_PHP_EXT_SOURCES \"{$d}/php-src/ext/base/base.c;{$d}/php-src/ext/fake/fake.c;{$d}/php-src/ext/fake/lib/a.c;{$d}/onig/src/regcomp.c\")\n", $inputs);
        self::assertStringContainsString("set(PHPBM_PHP_EXT_INCLUDE_DIRS \"{$d}/php-src/ext/base;{$d}/php-src/ext/fake;{$d}/onig/src\")\n", $inputs);
        self::assertStringContainsString("set(PHPBM_PHP_EXT_DEFINES \"FAKE_NO_CJK=1;HAVE_BASE=1;HAVE_FAKE=1\")\n", $inputs);
        self::assertStringContainsString('&fake_module_entry,', (string) file_get_contents("{$build}/php_extensions.c"));
        $header = (string) file_get_contents("{$build}/include/phpbm_options.h");
        self::assertStringContainsString("#define PHPBM_OPTION_FAKE_CJK 0\n", $header);
        self::assertStringContainsString("#define PHPBM_OPTION_FAKE_TABLES \"small\"\n", $header);

        $plain = Plans::plan(['php' => $d . '/php-src']);
        $plain = new BuildPlan($plain->projectDir, $plain->manifest, $plain->sdk, $plain->board, $plain->chip, $plain->runtime, $plain->storage, $plain->php, $plain->phpSourceDir, [], [], $build, false, $plain->options);
        $inputs = (string) file_get_contents(BuildInputs::write($plain));
        self::assertStringContainsString("set(PHPBM_PHP_EXT_TABLE \"\")\n", $inputs);
        self::assertFileDoesNotExist("{$build}/php_extensions.c");
    }

    public function test_a_pattern_that_matches_nothing_is_an_sdk_bug(): void
    {
        $this->expectException(SpecException::class);
        $this->expectExceptionMessage("php/8.4/extensions/base.json: 'sources' pattern 'ext/base/*.cc' matches no file");
        PhpExtensions::fromPlan(self::plan([], [self::extension('base', ['sources' => ['ext/base/*.cc']])]));
    }

    public function test_an_exclude_that_matches_nothing_is_an_sdk_bug(): void
    {
        $this->expectException(SpecException::class);
        $this->expectExceptionMessage("php/8.4/extensions/base.json: 'exclude' pattern 'ext/base/gone.c' matches no file");
        PhpExtensions::fromPlan(self::plan([], [self::extension('base', ['exclude' => ['ext/base/gone.c']])]));
    }

    public function test_a_missing_include_dir_is_an_sdk_bug(): void
    {
        $this->expectExceptionMessage("php/8.4/extensions/base.json: include dir 'ext/nope' not found");
        PhpExtensions::fromPlan(self::plan([], [self::extension('base', ['include-dirs' => ['ext/nope']])]));
    }

    public function test_an_unprepared_source_is_reported(): void
    {
        $plan = Plans::plan(['php' => self::dir() . '/php-src', 'phpExtensions' => [self::extension('fake')]]);
        $this->expectExceptionMessage("php/8.4/extensions/fake.json: the source 'onig' was not prepared for this build");
        PhpExtensions::fromPlan($plan);
    }

    public function test_conflicting_defines_are_reported(): void
    {
        $this->expectExceptionMessage("php extensions 'base' and 'fake' define HAVE_BASE differently");
        PhpExtensions::fromPlan(self::plan([], [self::extension('base'), self::extension('fake', ['defines' => ['HAVE_BASE' => 2]])]));
    }
}
